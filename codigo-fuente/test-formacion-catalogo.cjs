const { JSDOM } = require('jsdom');
const fs = require('fs');
const html = '<!doctype html><html><head></head><body>' + fs.readFileSync('talento-balu.html', 'utf8') + '</body></html>';
const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) process.exitCode = 1; };
const espera = (ms = 40) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const dom = new JSDOM(html, { runScripts: 'dangerously', pretendToBeVisual: true, url: 'https://ejemplo.test/', beforeParse(w) { w.scrollTo = () => {}; } });
  await espera(300); const w = dom.window, d = w.document;
  const click = async (el) => { const _e = [...d.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Entendido'); if (_e && _e !== el) { _e.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(100); }  if (!el) throw new Error('falta elemento'); el.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(150); };
  const boton = (t, i = 0) => [...d.querySelectorAll('button')].filter((x) => x.textContent.trim().includes(t))[i];
  const texto = () => d.body.textContent;
  const setValor = (el, v) => { const proto = el.tagName === 'SELECT' ? w.HTMLSelectElement.prototype : el.tagName === 'TEXTAREA' ? w.HTMLTextAreaElement.prototype : w.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(proto, 'value').set.call(el, v); el.dispatchEvent(new w.Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); };
  const tab = (t) => [...d.querySelectorAll('[role=tab]')].find((b) => b.textContent.includes(t));
  const dlg = () => d.querySelector('[role=dialog]');
  await click(boton('Gerente de RRHH', 0)); await espera(300);
  await click(boton('Formación'));
  ok(Boolean(tab('Participaciones') && tab('Catálogo') && tab('Talleres')), 'Formación tiene Participaciones, Catálogo y Talleres');
  await click(tab('Catálogo'));
  await click(boton('Nueva formación'));
  setValor(d.getElementById('fc-nombre'), 'Seguridad y salud LOPCYMAT'); setValor(d.getElementById('fc-tipo'), 'NORMATIVA'); setValor(d.getElementById('fc-horas'), '4'); setValor(d.getElementById('fc-vig'), '12');
  await click([...dlg().querySelectorAll('input[type=checkbox]')][0]);
  await click([...dlg().querySelectorAll('button')].find((b) => b.textContent.includes('Guardar')));
  ok(texto().includes('Seguridad y salud LOPCYMAT') && texto().includes('12 meses'), 'Formación creada en el catálogo con vigencia');
  await click(tab('Participaciones'));
  await click(boton('Registrar participación'));
  const sel = d.getElementById('pf-trab'); setValor(sel, sel.options[1].value);
  const sf = d.getElementById('pf-form'); setValor(sf, sf.options[1].value);
  setValor(d.getElementById('pf-prog'), '2026-01-10');
  await click([...dlg().querySelectorAll('button')].find((b) => b.textContent.includes('Guardar')));
  ok(texto().includes('Vencida'), 'Programada con fecha pasada y sin realizar se marca Vencida');
  await click(boton('Registrar participación'));
  const sel2 = d.getElementById('pf-trab'); setValor(sel2, sel2.options[2].value);
  const sf2 = d.getElementById('pf-form'); setValor(sf2, sf2.options[1].value);
  setValor(d.getElementById('pf-prog'), '2026-09-01'); setValor(d.getElementById('pf-est'), 'Completada');
  await click([...dlg().querySelectorAll('button')].find((b) => b.textContent.includes('Guardar')));
  ok(dlg() && texto().includes('Indique la fecha real'), 'Completada exige la fecha real de realización');
  setValor(d.getElementById('pf-real'), '2026-09-05');
  await click([...dlg().querySelectorAll('button')].find((b) => b.textContent.includes('Guardar')));
  ok(!dlg() && texto().includes('Completada') && Boolean(boton('Anotar corrección')), 'Completada queda cerrada: solo admite anotación de corrección');
  await click(boton('Anotar corrección'));
  setValor(d.getElementById('pf-corr'), 'Se corrige la fecha de realización'); await click(boton('Guardar anotación'));
  ok(!dlg(), 'La anotación de corrección se guarda sin alterar el registro');
  // Gerente de tienda registra solo su tienda
  await click(boton('Salir')); setValor(d.getElementById('login-tienda'), 'gerente.propatria'); await click(boton('Entrar')); await espera(300);
  await click(boton('Formación'));
  ok(Boolean(boton('Registrar participación')), 'El Gerente de Tienda puede registrar participaciones');
  await click(boton('Registrar participación'));
  const so = d.getElementById('pf-trab');
  ok(so.options.length > 1 && so.options.length < 25, 'Solo se listan trabajadores de su tienda (' + (so.options.length - 1) + ')');
  process.exit(process.exitCode || 0);
})();
