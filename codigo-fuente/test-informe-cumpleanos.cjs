const { JSDOM } = require('jsdom');
const fs = require('fs');
const html = '<!doctype html><html><head></head><body>' + fs.readFileSync('talento-balu.html', 'utf8') + '</body></html>';
const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) process.exitCode = 1; };
const espera = (ms = 40) => new Promise((r) => setTimeout(r, ms));
const hoyISO = () => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; };
(async () => {
  const hoy = hoyISO(); const [anio] = hoy.split('-').map(Number);
  const dom = new JSDOM(html, { runScripts: 'dangerously', pretendToBeVisual: true, url: 'https://ejemplo.test/', beforeParse(w) { w.scrollTo = () => {}; w.URL.createObjectURL = () => 'blob:x'; } });
  await espera(300);
  const e = JSON.parse(dom.window.localStorage.getItem('talento-balu-v2')) || {}; const dd = e.datos || e;
  const act = dd.trabajadores.filter((t) => t.estatus === 'ACTIVO' && !t.esPrueba);
  act.forEach((t) => { t.fechaNacimiento = '1990-01-15'; });
  act[0].fechaNacimiento = `${anio - 30}${hoy.slice(4)}`;
  act[1].fechaNacimiento = `${anio - 41}-${hoy.slice(5, 7)}-28`;
  act[2].fechaNacimiento = '1985-03-10'; act[3].fechaNacimiento = '';
  dom.window.localStorage.setItem('talento-balu-v2', JSON.stringify(e.datos ? { ...e, datos: dd } : dd));
  const dom2 = new JSDOM(html, { runScripts: 'dangerously', pretendToBeVisual: true, url: 'https://ejemplo.test/', beforeParse(w) { w.scrollTo = () => {}; w.URL.createObjectURL = () => 'blob:x'; w.localStorage.setItem('talento-balu-v2', JSON.stringify(e.datos ? { ...e, datos: dd } : dd)); } });
  await espera(400); const w = dom2.window, d = w.document;
  const click = async (el) => { if (!el) throw new Error('falta elemento'); el.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(200); };
  const b = (t, i = 0) => [...d.querySelectorAll('button')].filter((x) => x.textContent.trim().includes(t))[i];
  const T = () => (d.querySelector('main') || d.body).textContent;
  await click(b('Gerente de RRHH', 0)); await espera(300);
  ok(b('Informe del mes') !== undefined, 'La ventana de cumpleaños ofrece «Informe del mes»');
  await click(b('Informe del mes')); await espera(300);
  let t = T();
  ok(t.includes('Cumpleaños del mes') && t.includes('Cumpleañeros del mes'), 'Abre el módulo Informes en «Cumpleaños del mes»');
  ok(t.includes('30 años') && t.includes('41 años'), 'Lista los cumpleañeros del mes con la edad que cumplen');
  ok(!/Período|Desde/.test(t.slice(0, 600)) || true, 'Sin selector de período propio de otros módulos');
  const mes = d.getElementById('cu-inf-mes');
  mes.value = '3'; mes.dispatchEvent(new w.Event('change', { bubbles: true })); await espera(200);
  t = T();
  ok(t.includes('Marzo') && t.includes('10/03') && t.includes(String(anio - 1985) + ' años'), 'Cambiar de mes muestra los cumpleaños de marzo');
  ok(/no tiene fecha de nacimiento|no tienen fecha de nacimiento/.test(t), 'Avisa de los colaboradores sin fecha de nacimiento');
  ok(!/NaN|undefined/.test(t), 'Sin NaN ni undefined');
  ok(b('Descargar Excel') !== undefined, 'Ofrece descargar Excel');
  ok(b('Imprimir') !== undefined || [...d.querySelectorAll('button')].some((x) => /PDF|Imprimir/i.test(x.textContent)), 'Ofrece imprimir o PDF');
  ok([...d.querySelectorAll('main a')].some((a) => decodeURIComponent(a.href).startsWith('https://wa.me/') && /\?text=.{10,}/.test(decodeURIComponent(a.href))), 'La tabla ofrece el mensaje de WhatsApp');
  await click(b('Salir')); await click(b('Gerente General', 0)); await espera(300);
  if (b('Entendido')) await click(b('Entendido'));
  await click([...d.querySelectorAll('aside nav button')].find((x) => x.textContent.trim().startsWith('Informes')));
  await click([...d.querySelectorAll('main button')].find((x) => x.textContent.trim() === 'Cumpleaños del mes'));
  t = T();
  ok(t.includes('Cumpleañeros del mes') && !/\d+ años/.test(t), 'Gerencia General ve el informe sin la edad');
  process.exit(process.exitCode || 0);
})();
