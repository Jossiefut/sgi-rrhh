const { JSDOM } = require('jsdom');
const fs = require('fs');
const html = '<!doctype html><html><head></head><body>' + fs.readFileSync('talento-balu.html', 'utf8') + '</body></html>';
const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) process.exitCode = 1; };
const espera = (ms = 40) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const dom = new JSDOM(html, { runScripts: 'dangerously', pretendToBeVisual: true, url: 'https://ejemplo.test/', beforeParse(w) { w.scrollTo = () => {}; } });
  await espera(300); const w = dom.window, d = w.document;
  const click = async (el) => { const _e = [...d.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Entendido'); if (_e && _e !== el) { _e.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(100); } if (!el) throw new Error('falta elemento'); el.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(150); };
  const boton = (t, i = 0) => [...d.querySelectorAll('button')].filter((x) => x.textContent.trim().includes(t))[i];
  const texto = () => d.body.textContent;
  const setValor = (el, v) => { const proto = el.tagName === 'SELECT' ? w.HTMLSelectElement.prototype : w.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(proto, 'value').set.call(el, v); el.dispatchEvent(new w.Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); el.dispatchEvent(new w.Event('change', { bubbles: true })); };
  const entrar = async (rol) => { if (boton('Salir')) await click(boton('Salir')); await click(boton(rol, 0)); await espera(200); };
  const db = () => JSON.parse(w.localStorage.getItem('talento-balu-v2')).datos || JSON.parse(w.localStorage.getItem('talento-balu-v2'));
  await entrar('Administrador');
  const datos = db();
  const ase = datos.trabajadores.find((x) => x.cargoId === 'ASE' && x.estatus === 'ACTIVO' && !x.esPrueba);
  await click(boton('Solicitudes')); await click(boton('Nueva solicitud'));
  const tipos = [...d.getElementById('so-tipo').options].map((o) => o.value);
  ok(tipos.length === 9 && tipos.includes('NINEBOX') && tipos.includes('APOYO') && tipos.includes('PERNOCTA') && tipos.includes('EVAL_FIJO'), 'La nueva solicitud ofrece los 9 tipos');
  setValor(d.getElementById('so-buscar'), ase.cedula); await espera(); setValor(d.getElementById('so-trab'), ase.id); await espera();
  setValor(d.getElementById('so-tipo'), 'NINEBOX'); await espera();
  ok(d.querySelector('[role=dialog]') && d.querySelector('[role=dialog]').textContent.includes('Nine-Box no está habilitada para el cargo'), 'Nine-Box a un Asesor: alerta de emergencia con el motivo');
  ok(d.getElementById('so-tipo').value !== 'NINEBOX', 'El tipo no aplicable no queda seleccionado');
  await click(boton('Entendido'));
  ok(d.querySelectorAll('[role=dialog]').length === 0, 'La alerta se cierra');
  setValor(d.getElementById('so-tipo'), 'EVAL_FIJO'); await espera();
  const aviso = Boolean(d.querySelector('[role=dialog]'));
  const e = null;
  console.log(aviso ? '  (Pase a fijo no aplica a este trabajador: alerta mostrada)' : '  (Pase a fijo aplica a este trabajador)');
  if (aviso) await click(boton('Entendido'));
  setValor(d.getElementById('so-tipo'), 'APOYO'); await espera();
  ok(texto().includes('Continuar a apoyo de personal') || d.querySelector('[role=dialog]'), 'Apoyo: o se continúa al formulario o se alerta');
  await entrar('Administrador');
  console.log('fin');
  process.exit(process.exitCode || 0);
})();
