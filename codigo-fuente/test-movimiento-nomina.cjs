/* Traslado y promoción aprobados (firma de Gerencia General): el trabajador cambia de cargo y de tienda y pasa a la nómina (listado) de la tienda de destino. */
const { JSDOM } = require('jsdom');
const fs = require('fs');
const html = '<!doctype html><html><head></head><body>' + fs.readFileSync('talento-balu.html', 'utf8') + '</body></html>';
const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) process.exitCode = 1; };
const espera = (ms = 40) => new Promise((r) => setTimeout(r, ms));
let dom, w, d;
const crear = (estado) => {
  dom = new JSDOM(html, { runScripts: 'dangerously', pretendToBeVisual: true, url: 'https://ejemplo.test/', beforeParse(w0) { w0.scrollTo = () => {}; w0.URL.createObjectURL = () => 'blob:x'; w0.URL.revokeObjectURL = () => {}; if (estado) w0.localStorage.setItem('talento-balu-v2', estado); } });
  w = dom.window; d = w.document;
};
const click = async (el, ms = 120) => { const e = [...d.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Entendido'); if (e && e !== el) { e.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(100); } if (!el) throw new Error('falta elemento'); el.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(ms); };
const boton = (t, i = 0) => [...d.querySelectorAll('button')].filter((x) => x.textContent.trim().includes(t))[i];
const nav = (t) => [...d.querySelectorAll('aside nav button')].find((b) => b.textContent.trim().startsWith(t));
const estado = () => { const est = JSON.parse(w.localStorage.getItem('talento-balu-v2')); return est.datos || est; };
const setValor = async (el, vv) => { const proto = Object.getPrototypeOf(el); Object.getOwnPropertyDescriptor(proto, 'value').set.call(el, vv); el.dispatchEvent(new w.Event('input', { bubbles: true })); el.dispatchEvent(new w.Event('change', { bubbles: true })); await espera(150); };
(async () => {
  crear(); await espera(400);
  const raw = JSON.parse(w.localStorage.getItem('talento-balu-v2')); const dd = raw.datos || raw; dom.window.close();
  const base = dd.solicitudes.find((s) => s.id === 'S001');
  const aprobada = (s) => { const pasos = JSON.parse(JSON.stringify(s.pasos)); pasos.forEach((p, i) => { if (i < pasos.length - 1) Object.assign(p, { estado: 'APROBADO', usuarioId: 'rrhh', fecha: '2026-10-12T10:00' }); }); return { ...s, pasos, pasoActual: pasos.length - 1, estado: 'EN_REVISION' }; };
  ok(base.pasos[base.pasos.length - 1].tipo === 'FIRMA', 'La ruta del traslado termina en la firma de Gerencia General');
  const trasl = aprobada(base);
  const trT = dd.trabajadores.find((x) => x.id === trasl.trabajadorId);
  const otro = dd.trabajadores.find((x) => x.estatus === 'ACTIVO' && !x.esPrueba && x.tiendaId === 'T01' && x.id !== trT.id);
  const cargoNuevo = dd.cargos.find((c) => c.id !== otro.cargoId && c.id !== 'ASE').id;
  const promo = { ...aprobada(base), id: 'S-PRO-1', tipo: 'PROMOCION', trabajadorId: otro.id, datosPropuestos: { cargoDestinoId: cargoNuevo, tiendaDestinoId: 'T08', motivo: 'Ascenso con cambio de sede', diasFormacion: 30 } };
  dd.solicitudes = dd.solicitudes.map((s) => (s.id === 'S001' ? trasl : s)); dd.solicitudes.push(promo);
  if (raw.datos) raw.datos = dd;
  const origenT = trT.tiendaId; const cargoT = trT.cargoId; const origenP = otro.tiendaId;
  ok(origenT !== 'T07' && origenP !== 'T08', `Antes: ${trT.nombres} en ${origenT} (traslado a T07); ${otro.nombres} en ${origenP} (promoción a T08)`);
  crear(JSON.stringify(raw)); await espera(400);
  await click(boton('Gerente General'), 250);
  await click(boton('Pendientes de mi aprobación'), 200);
  const ejecutar = async (id) => {
    await click([...d.querySelectorAll('tr')].find((r) => r.textContent.includes(id)), 250);
    await click(boton('Aprobar', 0));
    const dlg = [...d.querySelectorAll('[role=dialog]')].pop();
    const chk = dlg.querySelector('input[type=checkbox]'); if (chk) await click(chk, 100);
    await click([...[...d.querySelectorAll('[role=dialog]')].pop().querySelectorAll('button')].find((b) => b.textContent.trim().startsWith('Aprobar')), 300);
  };
  await ejecutar('S-PRO-1');
  let e = estado();
  let p = e.trabajadores.find((x) => x.id === otro.id);
  ok(p.cargoId === cargoNuevo && p.tiendaId === 'T08', 'Promoción ejecutada: el trabajador cambia de cargo y de tienda');
  ok(p.tiendaIngresoId === otro.tiendaIngresoId, 'Se conserva la tienda original de ingreso (para los reportes de ingresos)');
  ok(p.historial.some((h) => h.tipo === 'PROMOCION' && /T08|Tienda 08|en /.test(h.detalle)), 'Queda registrada la promoción en su historial');
  if (boton('Volver')) await click(boton('Volver'), 200);
  if (!boton('Pendientes de mi aprobación') && nav('Inicio')) await click(nav('Inicio'), 250);
  if (boton('Pendientes de mi aprobación')) await click(boton('Pendientes de mi aprobación'), 200);
  await ejecutar('S001');
  e = estado();
  const t = e.trabajadores.find((x) => x.id === trT.id);
  ok(t.tiendaId === 'T07' && t.cargoId === cargoT, 'Traslado ejecutado: cambia de tienda y conserva el cargo');
  ok(t.historial.some((h) => h.tipo === 'TRASLADO'), 'Queda registrado el traslado en su historial');
  /* Aparece en el listado (nómina) de la tienda de destino y sale del de origen */
  await click(nav('Directorio'), 250);
  const filaDe = (nombre) => [...d.querySelectorAll('main table tbody tr')].some((r) => r.textContent.includes(nombre));
  const nomT = `${trT.apellidos}`; const nomP = `${otro.apellidos}`;
  await setValor(d.querySelector('#dir-tienda'), 'T07');
  ok(filaDe(nomT), 'El trabajador trasladado aparece en la nómina de la tienda de destino (T07)');
  await setValor(d.querySelector('#dir-tienda'), origenT);
  ok(!filaDe(nomT), 'Ya no aparece en la nómina de la tienda de origen');
  await setValor(d.querySelector('#dir-tienda'), 'T08');
  ok(filaDe(nomP), 'El trabajador promovido aparece en la nómina de la tienda de destino (T08)');
  await setValor(d.querySelector('#dir-tienda'), origenP);
  ok(!filaDe(nomP), 'El promovido ya no aparece en la nómina de su tienda anterior');
  console.log(process.exitCode ? '\nHAY FALLAS' : '\nTodo correcto');
  process.exit(process.exitCode || 0);
})().catch((e) => { console.error('✗ Error:', e); process.exit(1); });
