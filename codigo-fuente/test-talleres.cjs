const { JSDOM } = require('jsdom');
const fs = require('fs');
const html = '<!doctype html><html><head></head><body>' + fs.readFileSync('talento-balu.html', 'utf8') + '</body></html>';
const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) process.exitCode = 1; };
const espera = (ms = 40) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const dom = new JSDOM(html, { runScripts: 'dangerously', pretendToBeVisual: true, url: 'https://ejemplo.test/', beforeParse(w) { w.scrollTo = () => {}; w.URL.createObjectURL = () => 'blob:x'; w.URL.revokeObjectURL = () => {}; } });
  await espera(300); const w = dom.window, d = w.document;
  const click = async (el) => { const _e = [...d.querySelectorAll('button')].find((b) => b.textContent.trim() === 'Entendido'); if (_e && _e !== el) { _e.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(100); }  if (!el) throw new Error('falta elemento'); el.dispatchEvent(new w.MouseEvent('click', { bubbles: true })); await espera(150); };
  const boton = (t, i = 0) => [...d.querySelectorAll('button')].filter((x) => x.textContent.trim().includes(t))[i];
  const nav = (t) => [...d.querySelectorAll('aside nav button')].find((b) => b.textContent.trim().startsWith(t));
  const texto = () => d.body.textContent;
  const setValor = (el, v) => { const proto = el.tagName === 'SELECT' ? w.HTMLSelectElement.prototype : w.HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(proto, 'value').set.call(el, v); el.dispatchEvent(new w.Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); el.dispatchEvent(new w.Event('change', { bubbles: true })); };
  const blur = async (el) => { el.dispatchEvent(new w.FocusEvent('focusout', { bubbles: true })); el.dispatchEvent(new w.FocusEvent('blur')); await espera(150); };
  const entrar = async (rol) => { if (boton('Salir')) await click(boton('Salir')); await click(boton(rol, 0)); await espera(200); };
  await entrar('Gerente de RRHH');
  await click(nav('Formación'));
  await click([...d.querySelectorAll('[role=tab]')].find((x) => x.textContent.trim().startsWith('Talleres')));
  await click(boton('Nuevo taller'));
  setValor(d.getElementById('tl-nombre'), 'Taller de servicio al cliente'); setValor(d.getElementById('tl-fac'), 'Equipo de Formación'); await espera();
  await click(boton('Crear taller'));
  ok(texto().includes('Taller de servicio al cliente') && texto().includes('Horas del taller'), 'RRHH crea un taller');
  const cajas = () => [...d.querySelectorAll('input[id^="fo-c-"]')];
  ok(cajas().length > 3 && !d.getElementById('fo-agregar'), 'Hay una lista con casillas para marcar asistentes (sin escribir)');
  const cedulaDe = (cb) => { const id = cb.id.replace('fo-c-', ''); return id; };
  await click(cajas()[0]); await click(cajas()[1]);
  ok(boton('Agregar marcados (2)'), 'El botón cuenta los marcados');
  await click(boton('Agregar marcados'));
  ok(d.querySelectorAll('tbody tr').length >= 2 && texto().includes('Falta indicar horas'), 'Asistentes agregados con casillas; sin horas no hay certificado');
  const antes = d.querySelectorAll('tbody tr').length;
  await click(d.getElementById('fo-todos'));
  ok(boton('Agregar marcados (') && /Agregar marcados \((\d+)\)/.test(texto()) && Number(/Agregar marcados \((\d+)\)/.exec(texto())[1]) > 3, 'Seleccionar todos marca a todos los visibles');
  await click(d.getElementById('fo-todos'));
  // Importar desde Excel/CSV: una cédula elegible y otra que no existe
  const est = JSON.parse(w.localStorage.getItem('talento-balu-v2')); const dd = est.datos || est;
  const ocupados = new Set((dd.talleres.slice(-1)[0].asistentes || []).map((a) => a.trabajadorId));
  const cand = cajas()[0].id.replace('fo-c-', ''); const trab = dd.trabajadores.find((t) => t.id === cand);
  const csv = 'Cédula,Nombre\n' + trab.cedula + ',Prueba\n99999999,Inexistente\n';
  const inp = d.getElementById('fo-excel'); const archivo = new w.File([csv], 'asistentes.csv', { type: 'text/csv' });
  Object.defineProperty(inp, 'files', { value: [archivo], configurable: true }); inp.dispatchEvent(new w.Event('change', { bubbles: true })); await espera(600);
  ok(texto().includes('asistentes.csv: 1 agregados') && texto().includes('99999999'), 'La importación agrega la cédula válida y avisa de la que no corresponde');
  ok(d.querySelectorAll('tbody tr').length === antes + 1, 'La persona importada quedó en la lista de asistentes');
  const h = d.getElementById('tl-horas'); setValor(h, '4'); await blur(h);
  const nota = d.querySelector('input[aria-label^="Calificación"]'); setValor(nota, '17'); await blur(nota);
  ok(texto().includes('Aprobado'), 'La calificación se ve con su resultado (17 de 20: aprobado)');
  await click(boton('Certificado'));
  await espera(800);
  ok(d.querySelector('[role=dialog]') && /Certificado de asistencia/i.test(d.querySelector('[role=dialog]').textContent), 'Se genera el certificado de asistencia');
  await click(boton('Vista del documento')); await espera(200);
  const dlg = d.querySelector('[role=dialog]').textContent;
  ok(dlg.includes('Taller de servicio al cliente') && dlg.includes('4 horas') && dlg.includes('17'), 'El certificado muestra taller, horas y calificación');
  await click(boton('Salir')); setValor(d.getElementById('login-tienda'), 'gerente.propatria'); await espera(); await click(boton('Entrar')); await espera(200);
  ok(Boolean(nav('Formación')), 'La tienda ve el módulo Formación');
  await click(nav('Formación'));
  { const tl = [...d.querySelectorAll('[role=tab]')].find((x) => x.textContent.trim().startsWith('Talleres')); if (tl) await click(tl); }
  ok(Boolean(boton('Nuevo taller')), 'La tienda puede crear talleres y marcar asistencia');
  console.log('fin');
  process.exit(process.exitCode || 0);
})();
